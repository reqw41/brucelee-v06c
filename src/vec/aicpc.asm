; aicpc.asm: ближний бой врагов как у CPC (решение владельца 06.11.2026 «сложность как в CPC»), в странице 0.
; У ZX (D6D4) враг в ряду Брюса бьёт только с расстояния ровно 2 (рукой) или 4 (ногой) знакоместа, иначе идёт к
; нему; разворот — пауза 0x32 шагов. У CPC (6F83..7017): слишком близко — отходит; на дистанции удара развернётся к
; Брюсу (пауза 0x0F) и бьёт с вероятностью 1/4 за решение (иначе стоит, выжидая); дальше — подходит. Дистанции
; ударов — ZX (столкновения ZX): рукой 2, ногой 3..4 знакоместа. Пауза разворота 0x0F — AI_TURN (pers.asm).
; Вход — из ai.near (враг в ряду Брюса); выход — желаемое действие в A, как у ai.
ai_cpc:		ld	a,(P_X)
			ld	b,a
			ld	a,(zc_CCAB)
			ld	c,0x11				; C — удар ногой в сторону Брюса: 11 вправо, 12 влево
			sub	b
			jp	nc,.p
			cpl
			inc	a
			inc	c
.p:			ld	b,a					; B = расстояние
			cp	2
			jp	nc,.n
			ld	a,c					; ближе 2 — отойти (CPC 6FAB / 7007)
			xor	3
			ld	c,a
.n:			ld	a,(P_DIR)			; лицом не туда — развернуться (CPC 6FC5)
			add	a,0x11
			cp	c
			jp	nz,ai.turn
			ld	a,b					; ближе 2 или дальше 4 — идти (стена — стоять)
			sub	2
			cp	3
			jp	nc,ai.walk
			jp	ai_cpc2

AI_P		equ	3					; маска случая: 1/4 за решение, как CPC (6FBD)
	MACRO	AI_CPC2					; хвост страницы 0 (после roompal.asm)
ai_cpc2:	dec	b
			dec	b
			jp	nz,.k
			call	plat_rand			; 2: удар рукой с вероятностью AI_P (CPC 6FBD: LD A,R / AND 3), иначе стоять
			and	AI_P
			ld	a,0
			ret	nz
			ld	a,0x10
			ret
.k:			ld	a,(pcur)			; 3..4: у ZX удар ногой — только с разбега (h_CE48: ходьба, P_C0D >= 2),
			cp	low NINJA			; (IS_CUR NINJA: макрос ниже по тексту)
			jp	z,ai.walk			; Ниндзя ногой не бьёт — подойти на 2
			jp	ai_cpc3
	ENDM

	MACRO	AI_CPC3					; дыра 8 (за sfx_die)
ai_cpc3:	ld	a,(P_ST)			; Ямо: стоит — шаг к Брюсу; идёт — удар ногой в его сторону (C)
			cp	2
			jp	c,ai.walk
			ld	a,c
			ret
	ENDM
