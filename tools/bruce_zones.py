# Раскраска Брюса (решение владельца 05.11.2026): три цвета — кожа жёлтая, одежда (штаны) белая, волосы и пояс красные.
# Правило по частям кадра; кадры — описатели Брюса по возрастанию адреса (0..15), координаты — точки кадра стороны 0
# (вправо). Сторона 1 — зеркало по ширине кадра (кадр 12 нарисован отдельно — те же зоны без зеркала).
#   ('U', верх, пояс[, x0, x1])  стоя: строки верх..верх+3 — волосы (только x0..x1, если заданы), до пояса — кожа,
#                                 пояс..пояс+1 — пояс, ниже — штаны
#   ('H', x_голова, y_волосы, x_пояс)  лёжа/в прыжке головой влево: x <= x_голова и y <= y_волосы — волосы,
#                                 x < x_пояс — кожа, x_пояс..x_пояс+1 — пояс, правее — штаны
#   ('R', x_голова, y_волосы, x_пояс)  то же головой вправо: x >= x_голова и y <= y_волосы — волосы, x > x_пояс + 1 —
#                                 кожа, x_пояс..x_пояс+1 — пояс, левее — штаны
ZONES = {
    0: ('U', 2, 14), 1: ('U', 2, 14), 2: ('U', 3, 14),
    3: ('H', 9, 5, 11), 4: ('H', 9, 5, 11), 5: ('H', 9, 6, 10), 6: ('H', 9, 6, 10),
    7: ('R', 17, 3, 11),
    8: ('U', 0, 11), 9: ('U', 0, 11), 10: ('U', 2, 14), 11: ('U', 3, 15),
    12: ('U', 0, 12, 4, 11), 13: ('U', 2, 13), 14: ('U', 2, 13), 15: ('U', 2, 14),
}
NO_MIRROR = {12}
R, Y, W = 2, 6, 7        # цвета ZX: красный (C000), жёлтый (C000 + A000), белый (все три)


def colour(n, x, y, w):
    """Цвет точки (x, y) кадра n стороны 0 шириной w точек."""
    z = ZONES[n]
    if z[0] == 'U':
        top, belt = z[1], z[2]
        x0, x1 = (z[3], z[4]) if len(z) > 3 else (0, w - 1)
        if y <= top + 3 and x0 <= x <= x1: return R
        if y < belt: return Y
        if y <= belt + 1: return R
        return W
    xh, yh, xb = z[1], z[2], z[3]
    if z[0] == 'H':
        if x <= xh and y <= yh: return R
        if x < xb: return Y
        if x <= xb + 1: return R
        return W
    if x >= xh and y <= yh: return R
    if x > xb + 1: return Y
    if x >= xb: return R
    return W
