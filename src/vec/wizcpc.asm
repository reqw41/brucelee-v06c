;  wizcpc.asm: стрельба колдуна как у CPC (владелец 07.11; разбор BRUCE.N02 7D01..7DFE): выстрел без долгой паузы,
;  огонь опускается на ряд раз в 3 прохода (CPC — 8 строк раз в 3 кадра), 5 направлений — наклон -1, -1/2, 0, +1/2, +1
;  клетки на ряд (1/2 — сдвиг через ряд) по столбцу Брюса в момент выстрела. Полёт и попадание — код ZX (r_DD0D.mv) со
;  своим шагом FE19. Части — по свободным местам (9200 и неиспользуемые глифы шрифта); в run80 не выполняется.
wiz_cpc:	ld	a,(zv_FE3C)			; 0 — новый выстрел; 1..8 — пауза; дальше ряд раз в 3 прохода (6 -> 9)
			or	a
			jp	z,wiz_nw0
			inc	a
			ld	(zv_FE3C),a
			cp	9
			ret	c
			ld	a,6
			ld	(zv_FE3C),a
			ld	a,(zv_FE18)			; ряд: чётный / нечётный
			and	1
			ld	c,a
			ld	a,(wiz_dir)			; направление * 2
			add	a,c
			ld	e,a
			ld	d,0
			ld	hl,wiz_stp
			add	hl,de
			ld	a,(hl)
			ld	(zv_FE19),a
			jp	r_DD0D.mv
wiz_dir:	db	0
