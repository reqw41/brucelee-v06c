def cpc_frame(i, face=False, raw=False):
    """Кадр CPC i (или свой, CUSTOM) -> список строк, в строке — 'Y'/'K'/None на точку Вектора (точка CPC — 2 точки)."""
    if face:
        o = cpc_frame(i, raw=True); assert len(FACE[i]) == len(o) and all(len(r) == len(o[0]) for r in FACE[i]), 'лицо: размер кадра'
        return [[{'#': 'K', 'o': 'Y', '.': None}[ch] for ch in row] for row in FACE[i]]
    if i in EDIT and not raw:
        o = cpc_frame(i, raw=True); assert len(EDIT[i]) == len(o) and all(len(r) == len(o[0]) for r in EDIT[i]), 'правка: размер кадра'
        return [[{'#': 'K', 'o': 'Y', '.': None}[ch] for ch in row] for row in EDIT[i]]
    if i in CUSTOM:
        return [[v for c in row for v in ([{'G': 'Y', 'Y': 'Y', '#': 'K'}.get(c)] * 2)] for row in CUSTOM[i]]
    a = cw(0x4800 + 2 * i); w = cb(a); rows = []
    for r in range(23):
        row = []
        for c in range(w):
            b = cb(a + 1 + r * w + c)
            for p in (((b >> 7) & 1) | (((b >> 3) & 1) << 1) | (((b >> 5) & 1) << 2) | (((b >> 1) & 1) << 3),
                      ((b >> 6) & 1) | (((b >> 2) & 1) << 1) | (((b >> 4) & 1) << 2) | ((b & 1) << 3)):
                v = PEN.get(p) if p else None
                row += [v, v]
        rows.append(row)
    return rows


def place(img, d, side, f, snap=False, face=False):
    """Описатель ZX d (образ img), сторона, кадр CPC f -> (Y, K): списки 8h строк по w*8 точек (bool)."""
    w, h = img[d], img[d + 1]; W, H = w * 8, h * 8
    zx = [[False] * W for _ in range(H)]
    for j in range(w):
        for r in range(h):
            g = img[d + 2 + r * w + j]; a = 0xA000 + g * 8           # сторона 0
            for k in range(8):
                m, px = img[a + 0x1000 + k], img[a + k]
                for b in range(8): zx[r * 8 + k][j * 8 + b] = bool((px >> (7 - b)) & 1 or not (m >> (7 - b)) & 1)
    fr = cpc_frame(f, raw=True)          # привязка — по исходному кадру CPC (правки EDIT/FACE её не сдвигают)
    ys = [y for y, row in enumerate(fr) if any(row)]; xs = [x for x in range(len(fr[0])) if any(row[x] for row in fr)]
    y0, y1, x0, x1 = ys[0], ys[-1], xs[0], xs[-1]
    # привязка: по вертикали низ фигуры CPC — к низу фигуры ZX; по горизонтали центр головы (верхние 8 строк
    # фигуры) CPC — к центру головы ZX. Так сохраняется сдвиг внутри кадров ZX, на котором держится плавность
    # движения (ZX шагает на клетку, кадры ходьбы нарисованы со сдвигом), а соседние кадры не скачут.
    # Точки ZX — без маски (zp), у CPC — все точки кадра.
    zp = [[False] * W for _ in range(H)]
    for j in range(w):
        for r in range(h):
            g = img[d + 2 + r * w + j]; a = 0xA000 + g * 8
            for k in range(8):
                for b in range(8): zp[r * 8 + k][j * 8 + b] = bool((img[a + k] >> (7 - b)) & 1)
    def head(rows):
        ys = [y for y, row in enumerate(rows) if any(row)]
        xs = [x for y in ys[:8] for x, v in enumerate(rows[y]) if v]
        return sum(xs) / len(xs), ys[-1]
    (zc, zb), (cc, cb) = head(zp), head(fr)
    dx = round(zc - cc)
    if snap: dx = 8 * round(dx / 8)      # snap: сдвиг кратен 8 — кадр шириной 16 точек ложится в 2 байта (память)
    best = (0, dx, zb - cb)
    y0, y1, x0, x1 = 0, len(fr) - 1, 0, len(fr[0]) - 1
    _, dx, dy = best
    fr = cpc_frame(f, face)              # точки — с правками владельца (и с лицом в финале)
    pix = {}                             # (X, Y) -> 'Y' / 'K' относительно левого верхнего угла рамки ZX (может выходить за неё)
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            v = fr[y][x]
            if v:
                X, Y = x + dx, y + dy
                if side: X = W - 1 - X
                pix[X, Y] = v
    return pix
